DATA = Path(__file__).parent / "data"
RESULTS = DATA / "results-synthetic.csv"
PREV = DATA / "previous-synthetic.yaml"
SRC = "Synthetic certified results (test fixture)"
HEAD = "chamber,state,district,name,party,bioguide_id,caucus"


def build(**kw: object) -> dict[str, Member]:
    args: dict[str, object] = {
        "previous": [PREV],
        "allow_missing": True,
        "senate_holdovers": True,
        "vacate": ["S000014"],
        "caucus": {"I": "D"},
    }
    args.update(kw)
    rep = build_from_results(RESULTS, SRC, "test-new", **args)  # type: ignore[arg-type]
    return {m.id: m for b in rep.comp.bodies.values() for m in b.roster}


def write(tmp_path: Path, *rows: str) -> Path:
    p = tmp_path / "results.csv"
    p.write_text("\n".join([HEAD, *rows]) + "\n")
    return p


def test_matching_placeholders_and_vacancies() -> None:
    rep = build_from_results(
        RESULTS,
        SRC,
        "test-new",
        previous=[PREV],
        caucus={"I": "D"},
        allow_missing=True,
        senate_holdovers=True,
        vacate=["S000014"],
        as_of=dt.date(2027, 1, 3),
    )
    house = {m.id: m for m in rep.comp.bodies["house"].roster}
    senate = {m.id: m for m in rep.comp.bodies["senate"].roster}
    # returning by bioguide id: no flag
    assert house["A000001"].notes is None
    # returning by name + state, flagged
    assert house["B000002"].party == "D"  # "Democratic" -> D
    assert "by name and state" in (house["B000002"].notes or "")
    # two previous CHARLIEs in AA: never guess
    assert "C000003" not in house and "D000004" not in house
    assert "ambiguous" in (house["new:AA-03"].notes or "")
    # caucus column beats --caucus I=D
    assert house["new:AA-05"].caucus == "R"
    # bioguide id not in previous; AL stored as district 1
    assert house["G000777"].district == 1
    assert "not in the previous" in (house["G000777"].notes or "")
    assert not any(m.state == "DC" for m in house.values())
    # blank row AA-04 is a vacancy; unlisted seats too (allow_missing)
    assert rep.comp.bodies["house"].vacancies == 435 - 5
    # senate: name match, placeholder, holdover (TWO in AA, THREE in BB; FOUR vacated)
    assert set(senate) == {"S000011", "new:BB-S1", "S000012", "S000013"}
    assert senate["S000013"].caucus == "D"  # previous caucus kept for a holdover
    assert senate["S000012"].notes == "holdover from the previous composition"
    text = "\n".join(rep.lines)
    assert rep.lines[0].startswith(f"Data: {SRC}. Accessed ")
    assert "Files: results-synthetic.csv." in rep.lines[0]
    assert "previous-synthetic.yaml (synthetic-previous, as of 2026-01-03)" in text
    assert "house: 5 members (3R/1D/1I), 430 vacancies" in text
    assert "vacant seat: AA-04 (blank row, line 5)" in text
    assert "not in results: 429 seats" in text
    assert "skipped: DC Dee Delegate: non-voting delegate" in text
    assert "holdovers from --previous: 2" in text


def test_round_trip_and_header(tmp_path: Path) -> None:
    rep = build_from_results(
        RESULTS,
        SRC,
        "test-new",
        previous=[PREV],
        allow_missing=True,
        accessed=dt.date(2027, 1, 2),
    )
    text = dump_composition(rep)
    assert text.startswith("# Generated by impsolver roster.\n# Data: Synthetic certified")
    assert "Accessed 2027-01-02" in text
    out = tmp_path / "c.yaml"
    out.write_text(text)
    c = load_composition(out)
    assert c.name == "test-new" and "new:AA-03" in {m.id for m in c.bodies["house"].roster}
    assert c.bodies["senate"].vacancies == 98  # no holdovers without the flag


def test_without_previous_everyone_new_or_by_id() -> None:
    got = build(previous=None, senate_holdovers=False, vacate=None)
    assert "A000001" in got and "new:AA-02" in got and "new:AA-S1" in got
    assert got["A000001"].notes is None  # nothing to compare against, so no flag
    assert got["new:AA-05"].caucus == "R"


def test_party_mapping_flag_and_member_caucus(tmp_path: Path) -> None:
    p = write(tmp_path, "house,AA,1,Ida Indy,I,I000001,", "house,AA,2,Jo Jay,I,J000002,")
    rep = build_from_results(
        p, SRC, "x", caucus={"I": "D"}, member_caucus={"J000002": "none"}, allow_missing=True
    )
    h = {m.id: m for m in rep.comp.bodies["house"].roster}
    assert h["I000001"].caucus == "D" and "party mapping" in (h["I000001"].notes or "")
    assert h["J000002"].caucus is None
    assert any("caucus from party mapping: Ida Indy" in ln for ln in rep.lines)
    with pytest.raises(ValueError, match="--member-caucus ids not found"):
        build_from_results(p, SRC, "x", member_caucus={"Z000009": "R"}, allow_missing=True)


def test_full_results_need_no_flag(tmp_path: Path) -> None:
    rows = [f"house,AA,{d},Rep {d},R,," for d in range(1, 436)]
    rows += [f"senate,{chr(81 + i // 26)}{chr(65 + i % 26)},,Sen {i},D,," for i in range(50)]
    rows += [f"senate,{chr(81 + i // 26)}{chr(65 + i % 26)},,Sen {i}b,D,," for i in range(50)]
    rows[0] = "house,AA,1,,,,"  # one vacancy
    rep = build_from_results(write(tmp_path, *rows), SRC, "full")
    assert rep.comp.bodies["house"].vacancies == 1
    assert rep.comp.bodies["senate"].vacancies == 0
    s = {m.id for m in rep.comp.bodies["senate"].roster}
    assert {"new:QA-S1", "new:QA-S2", "new:RX-S2"} <= s


@pytest.mark.parametrize(
    ("rows", "match"),
    [
        (["house,AA,1,A,R,,", "house,AA,01,B,D,,"], "2 rows for 1 seat"),
        (["senate,AA,,A,R,,", "senate,AA,,B,R,,", "senate,AA,,C,D,,"], "3 rows for 2 seat"),
        (["senate,AA,2,A,R,,"], "leave district blank"),
        (["house,AA,x,A,R,,"], "number or AL"),
        (["assembly,AA,1,A,R,,"], "house or senate"),
        (["house,AAA,1,A,R,,"], "2-letter"),
        (["house,AA,1,A,,,"], "has no party"),
        (["house,AA,1,A,R,abc,"], "bad bioguide_id"),
        (["house,AA,1,A,R,A000001,", "house,AA,2,B,R,A000001,"], "appears twice"),
    ],
)
def test_validation_errors(tmp_path: Path, rows: list[str], match: str) -> None:
    with pytest.raises(ValueError, match=match):
        build_from_results(write(tmp_path, *rows), SRC, "x", allow_missing=True)


