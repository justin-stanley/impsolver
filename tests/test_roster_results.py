def test_columns_checked(tmp_path: Path) -> None:
    p = tmp_path / "r.csv"
    p.write_text("chamber,state,name,party\nhouse,AA,A,R\n")
    with pytest.raises(ValueError, match="missing column"):
        build_from_results(p, SRC, "x")
    p.write_text("chamber,state,district,name,party,votes\nhouse,AA,1,A,R,10\n")
    with pytest.raises(ValueError, match="unknown column"):
        build_from_results(p, SRC, "x")


def test_holdover_ambiguity_and_flags() -> None:
    with pytest.raises(ValueError, match="senate BB: 2 previous senators"):
        build(vacate=None)
    with pytest.raises(ValueError, match="needs --previous"):
        build(previous=None)
    with pytest.raises(ValueError, match="--vacate ids not found"):
        build(vacate=["Z000001"])
    with pytest.raises(ValueError, match="applies only with --senate-holdovers"):
        build(senate_holdovers=False)


def test_surname_matching() -> None:
    assert surname("BEGICH, Nicholas J., III") == ["begich"]
    assert same_surname("Nick Begich III", "BEGICH, Nicholas J., III")
    assert same_surname("Derrick Van Orden", "VAN ORDEN, Derrick")
    assert same_surname("Cherfilus-McCormick, Sheila", "CHERFILUS-MCCORMICK, Sheila")
    assert same_surname("José Núñez", "NUNEZ, Jose")
    assert same_surname("Nick Begich, III", "BEGICH, Nicholas J., III")
    assert same_surname("John Smith, Jr.", "SMITH, John")
    assert same_surname("Smith, John, Jr.", "SMITH, John")
    assert not same_surname("Orden", "VAN ORDEN, Derrick")
    assert not same_surname("Ann Smith", "SMYTH, Ann")
    assert not same_surname("Ann Smith", ",")


def test_cli_end_to_end(tmp_path: Path) -> None:
    out = tmp_path / "c.yaml"
    r = subprocess.run(
        [
            sys.executable,
            "-m",
            "impsolver.cli",
            "roster",
            "--from-results",
            str(RESULTS),
            "--source",
            SRC,
            "--previous",
            str(PREV),
            "--senate-holdovers",
            "--vacate",
            "S000014",
            "--allow-missing",
            "--caucus",
            "I=D",
            "--name",
            "test-new",
            "--as-of",
            "2027-01-03",
            "--accessed",
            "2027-01-02",
            "--out",
            str(out),
        ],
        capture_output=True,
        text=True,
    )
    assert r.returncode == 0, r.stderr
    assert "name match: Bob van Bravo Jr." in r.stderr
    assert SRC in out.read_text()
    assert load_composition(out).as_of.isoformat() == "2027-01-03"


