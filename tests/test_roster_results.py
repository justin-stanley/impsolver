def test_placeholder_ids_work_in_a_scenario(tmp_path: Path) -> None:
    comp = tmp_path / "comp.yaml"
    rep = build_from_results(RESULTS, SRC, "test-new", previous=[PREV], allow_missing=True)
    comp.write_text(dump_composition(rep))
    scen = tmp_path / "scen.yaml"
    scen.write_text(
        "schema_version: 1\n"
        "target: {name: Example Official, office: cabinet_secretary}\n"
        "rules: us-federal\n"
        f"composition: {comp.name}\n"
        "party_priors:\n"
        "  R: {'*': 0.1}\n"
        "  D: {'*': 0.9}\n"
        "overrides:\n"
        "  'new:AA-03': {'*': 0.99}\n"
    )
    assert cli_main(["validate", "us-federal", str(comp), str(scen)]) == 0
    assert cli_main(["evaluate", str(scen)]) == 0


