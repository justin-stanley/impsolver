def test_seats_switch_vacancies_and_caucus(files: tuple[Path, Path]) -> None:
    m, v = files
    rep = build_roster([m], [v], caucus={"I": "D"})
    house = {x.id: x for x in rep.comp.bodies["house"].roster}
    assert "B000002" not in house and "C000003" in house  # the latest voter wins the seat
    assert house["D000004"].party == "R"  # party switch merged; later party kept
    assert "E000005" not in house  # stopped voting: suspected vacancy
    assert "G000007" not in house  # DC delegate excluded
    assert "H000008" in house  # no votes counts as newest
    assert house["F000006"].caucus == "D" and "party mapping" in (house["F000006"].notes or "")
    assert rep.comp.bodies["house"].vacancies == 435 - len(house)
    assert any("suspected vacancy: ECHO" in ln for ln in rep.lines)
    assert rep.comp.bodies["senate"].seats == 100


def test_keep_and_member_caucus(files: tuple[Path, Path]) -> None:
    m, v = files
    rep = build_roster(
        [m], [v], caucus={"I": "D"}, member_caucus={"F000006": "none"}, keep=["E000005"]
    )
    house = {x.id: x for x in rep.comp.bodies["house"].roster}
    assert "E000005" in house
    assert house["F000006"].caucus is None  # member mapping beats party mapping


def test_summary_header_round_trips(files: tuple[Path, Path], tmp_path: Path) -> None:
    m, v = files
    text = dump_composition(build_roster([m], [v]))
    assert text.startswith("# Generated by impsolver roster.\n# Data: Lewis, Jeffrey B.")
    assert "\n# house:" in text
    out = tmp_path / "comp.yaml"
    out.write_text(text)
    assert load_composition(out).name == "us-119"


def test_cli(files: tuple[Path, Path], tmp_path: Path) -> None:
    m, v = files
    out = tmp_path / "c.yaml"
    r = subprocess.run(
        [
            sys.executable,
            "-m",
            "impsolver.cli",
            "roster",
            "--members",
            str(m),
            "--votes",
            str(v),
            "--caucus",
            "328=D",
            "--as-of",
            "2026-11-27",
            "--out",
            str(out),
        ],
        capture_output=True,
        text=True,
    )
    assert r.returncode == 0, r.stderr
    assert "house:" in r.stderr and load_composition(out).as_of.isoformat() == "2026-11-27"


